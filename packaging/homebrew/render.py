#!/usr/bin/env python3
"""Write a Homebrew formula for copse.

Usage: render.py [--nightly] VERSION TAG SHA256SUMS > Formula/NAME.rb

VERSION is the build's version (2026.11.0, or 2026.11.09-dev+abc1234 for a nightly),
TAG the GitHub release it's published under (v2026.11.0, or "nightly"), and
SHA256SUMS that release's checksum file.

Without --nightly it writes `copse` (the latest release; `brew install --HEAD`
builds main from source). With --nightly it writes `copse-nightly` (the latest
daily build). Both install the prebuilt binary for the machine (macOS on Apple
Silicon or Intel, Linux on x86_64), and since both install a `copse` command,
each says it conflicts with the other.
"""
import sys
from urllib.parse import quote

TARGETS = {  # Homebrew's names for the machine -> our build target
    ("macos", "arm"): "aarch64-apple-darwin",
    ("macos", "intel"): "x86_64-apple-darwin",
    ("linux", "intel"): "x86_64-unknown-linux-gnu",
}

args = sys.argv[1:]
nightly = "--nightly" in args
args = [a for a in args if a != "--nightly"]
if len(args) != 3:
    sys.exit(__doc__)
version, tag, sums_path = args

sums = {}
for line in open(sums_path):
    digest, name = line.split()
    sums[name.lstrip("*")] = digest


def block(os_name, cpu):
    name = f"copse-{version}-{TARGETS[(os_name, cpu)]}.tar.gz"
    if name not in sums:
        sys.exit(f"{sums_path} has no checksum for {name}")
    url = f"https://github.com/Copse-SCM/copse/releases/download/{quote(tag)}/{quote(name)}"
    return f'''    on_{cpu} do
      url "{url}"
      sha256 "{sums[name]}"
    end'''


if nightly:
    class_name, other = "CopseNightly", "copse"
    desc = "Daily development build of copse, the fast version control system"
    extra = ""
    install = '    bin.install "copse"'
else:
    class_name, other = "Copse", "copse-nightly"
    desc = "Fast version control that works with git servers, with undo for everything"
    extra = '''  head do
    url "https://github.com/Copse-SCM/copse.git", branch: "main"
    depends_on "rust" => :build
  end

'''
    install = '''    if build.head?
      system "cargo", "install", *std_cargo_args
    else
      bin.install "copse"
    end'''

print(f'''# Generated by packaging/homebrew/render.py in Copse-SCM/copse; don't edit by hand.
class {class_name} < Formula
  desc "{desc}"
  homepage "https://github.com/Copse-SCM/copse"
  version "{version}"
  license "Apache-2.0"

{extra}  on_macos do
{block("macos", "arm")}
{block("macos", "intel")}
  end

  on_linux do
{block("linux", "intel")}
  end

  conflicts_with "{other}", because: "both install a `copse` command"

  def install
{install}
  end

  test do
    assert_match "copse", shell_output("#{{bin}}/copse --version")
    assert_match "copse #{{version}}", shell_output("#{{bin}}/copse --version") unless version.head?
    ENV["COPSE_AUTHOR"] = "Brew Test"
    ENV["COPSE_EMAIL"] = "brew@example.com"
    system bin/"copse", "init"
    (testpath/"hello.txt").write "hello\\n"
    system bin/"copse", "commit", "-m", "first"
    assert_match "first", shell_output("#{{bin}}/copse log --oneline")
  end
end''')
