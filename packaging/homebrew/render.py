#!/usr/bin/env python3
"""Write the Homebrew formula for a copse release.

Usage: render.py VERSION TAG SHA256SUMS > copse.rb

VERSION is the release's version (2026.11.0), TAG the GitHub release tag it's
published under (v2026.11.0, or "nightly" for testing), and SHA256SUMS that
release's checksum file. The formula installs the prebuilt binary for the machine
(macOS on Apple Silicon or Intel, Linux on x86_64); `brew install --HEAD` builds
main from source instead.
"""
import sys
from urllib.parse import quote

TARGETS = {  # Homebrew's names for the machine -> our build target
    ("macos", "arm"): "aarch64-apple-darwin",
    ("macos", "intel"): "x86_64-apple-darwin",
    ("linux", "intel"): "x86_64-unknown-linux-gnu",
}

version, tag, sums_path = sys.argv[1:4]
sums = {}
for line in open(sums_path):
    digest, name = line.split()
    sums[name.lstrip("*")] = digest

def asset(target):
    name = f"copse-{version}-{target}.tar.gz"
    if name not in sums:
        sys.exit(f"{sums_path} has no checksum for {name}")
    url = f"https://github.com/Copse-SCM/copse/releases/download/{quote(tag)}/{quote(name)}"
    return url, sums[name]

def block(os_name, cpu):
    url, digest = asset(TARGETS[(os_name, cpu)])
    return f'''    on_{cpu} do
      url "{url}"
      sha256 "{digest}"
    end'''

print(f'''# Generated by packaging/homebrew/render.py in Copse-SCM/copse for each release.
class Copse < Formula
  desc "Fast version control that works with git servers, with undo for everything"
  homepage "https://github.com/Copse-SCM/copse"
  version "{version}"
  license "Apache-2.0"

  head do
    url "https://github.com/Copse-SCM/copse.git", branch: "main"
    depends_on "rust" => :build
  end

  on_macos do
{block("macos", "arm")}
{block("macos", "intel")}
  end

  on_linux do
{block("linux", "intel")}
  end

  def install
    if build.head?
      system "cargo", "install", *std_cargo_args
    else
      bin.install "copse"
    end
  end

  test do
    assert_match "copse", shell_output("#{{bin}}/copse --version")
    assert_match "copse #{{version}}", shell_output("#{{bin}}/copse --version") unless version.head?
    ENV["COPSE_AUTHOR"] = "Brew Test"
    ENV["COPSE_EMAIL"] = "brew@example.com"
    system bin/"copse", "init"
    (testpath/"hello.txt").write "hello\\n"
    system bin/"copse", "commit", "-m", "first"
    assert_match "first", shell_output("#{{bin}}/copse log --oneline")
  end
end''')
